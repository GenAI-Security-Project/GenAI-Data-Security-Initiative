"""Generate INDEX.md, the browsable list of incidents, from ./entries/.

Usage:
    python build_index.py           # rewrite INDEX.md
    python build_index.py --check   # exit 1 if INDEX.md is out of date (CI)

Stdlib only. Entries are listed newest first, then by incident_id.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ENTRIES_DIR = ROOT / "entries"
INDEX_PATH = ROOT / "INDEX.md"
CROSSWALK_INCIDENTS = "https://genai-security-project.github.io/crosswalk/#/incidents"

HEADER = """# Incident Index

<!-- Generated by build_index.py from entries/*.json. Do not edit by hand. -->

Every incident in `entries/`. Regenerate with `python build_index.py` after adding or changing an entry;
CI fails if this file is out of date. See the [README](README.md) for the schema and the disclosure rule.

"""


def cell(text: str) -> str:
    """Make text safe inside a Markdown table cell."""
    return " ".join(str(text).split()).replace("|", "\\|")


def shown_date(entry: dict) -> str:
    date = str(entry.get("date", ""))
    precision = entry.get("precision", "day")
    return date[:4] if precision == "year" else date[:7] if precision == "month" else date


def row(entry: dict) -> str:
    incident_id = entry.get("incident_id", "")
    orgs = entry.get("affected_organizations") or []
    who = ", ".join(orgs) if orgs else ("*anonymized*" if entry.get("disclosure") == "anonymized" else "")
    urls = entry.get("source_urls") or []
    sources = " ".join(f"[{i}]({u})" for i, u in enumerate(urls, 1)) or cell(entry.get("source", ""))
    crosswalk = entry.get("crosswalk_id", "")
    cells = [
        f"[{incident_id}](entries/{incident_id}.json)",
        shown_date(entry),
        cell(entry.get("title", "")),
        cell(who),
        ", ".join(entry.get("dsgai_mapping") or []),
        ", ".join(entry.get("data_types_affected") or []),
        entry.get("disclosure", ""),
        sources,
        f"[{crosswalk}]({CROSSWALK_INCIDENTS})" if crosswalk else "",
    ]
    return "| " + " | ".join(cells) + " |"


def render(entries: list[dict]) -> str:
    entries = sorted(entries, key=lambda e: e.get("incident_id", ""))
    entries.sort(key=lambda e: str(e.get("date", "")), reverse=True)
    public = sum(1 for e in entries if e.get("disclosure") == "public")
    lines = [HEADER.rstrip("\n"), ""]
    if not entries:
        lines += ["*No incidents yet. See the [README](README.md) to contribute one.*", ""]
        return "\n".join(lines)
    lines += [
        f"**{len(entries)} incidents** ({public} public, {len(entries) - public} anonymized).",
        "",
        "| ID | Date | Title | Affected organization | DSGAI | Data affected | Disclosure | Sources | Crosswalk |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        *(row(e) for e in entries),
        "",
    ]
    return "\n".join(lines)


def load_entries() -> list[dict]:
    files = sorted(ENTRIES_DIR.glob("*.json")) if ENTRIES_DIR.is_dir() else []
    return [json.loads(p.read_text(encoding="utf-8")) for p in files]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if INDEX.md is out of date")
    args = parser.parse_args(argv)
    text = render(load_entries())
    if args.check:
        current = INDEX_PATH.read_text(encoding="utf-8").replace("\r\n", "\n") if INDEX_PATH.is_file() else ""
        if current != text:
            print("INDEX.md is out of date: run `python build_index.py` in datasets/incident_dataset/ and commit it.")
            return 1
        print("INDEX.md is up to date.")
        return 0
    INDEX_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {INDEX_PATH.name}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
